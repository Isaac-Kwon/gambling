import { resolveHandoff, summarize, type Summary } from '../../shared/handoff';
import type { Session } from '../../shared/schema';

/** Where the page's data came from. `none` offers the demo session. */
export type Source =
  | { kind: 'full'; session: Session; summary: Summary }
  | { kind: 'summary'; summary: Summary }
  | { kind: 'demo'; session: Session; summary: Summary }
  | { kind: 'none' };

export type DataSource = Exclude<Source, { kind: 'none' }>;

const STASH_KEY = 'eg.u.hash';

function safeStorage(kind: 'local' | 'session'): Storage | null {
  try {
    return kind === 'local' ? localStorage : sessionStorage;
  } catch {
    return null;
  }
}

/** Is the demo requested through the URL (`?demo=1`)? */
export function wantsDemo(search: string): boolean {
  const v = new URLSearchParams(search).get('demo');
  return v === '1' || v === 'true';
}

// import.meta.glob keeps the build working while demo/session.json (generated by another task) does not exist yet.
const demoFiles = import.meta.glob<{ default: Session }>('./demo/session.json');

export async function loadDemo(): Promise<DataSource | null> {
  const load = demoFiles['./demo/session.json'];
  if (!load) return null;
  try {
    const session = (await load()).default;
    if (!session || !Array.isArray(session.events)) return null;
    return { kind: 'demo', session, summary: summarize(session) };
  } catch {
    return null;
  }
}

export function demoAvailable(): boolean {
  return './demo/session.json' in demoFiles;
}

/**
 * Handoff order: `#s=` hash (full session in localStorage wins when it matches), then localStorage,
 * then a summary stashed in sessionStorage by an earlier load of this page (the hash is stripped after reading),
 * then `?demo=1`, else none.
 */
export async function resolveSource(hash: string, search: string): Promise<Source> {
  const ls = safeStorage('local');
  const ss = safeStorage('session');
  let effectiveHash = hash;
  if (!/(^|[#&])s=/.test(hash)) {
    try {
      const stash = ss?.getItem(STASH_KEY);
      if (stash) effectiveHash = stash;
    } catch { /* ignore */ }
  }
  if (!wantsDemo(search)) {
    try {
      const h = await resolveHandoff(effectiveHash, ls);
      if (h?.kind === 'full') return { kind: 'full', session: h.session, summary: summarize(h.session) };
      if (h?.kind === 'summary') {
        try {
          const m = /(?:^|[#&])(s=[^&]+)/.exec(effectiveHash);
          if (m) ss?.setItem(STASH_KEY, '#' + m[1]);
        } catch { /* ignore */ }
        return { kind: 'summary', summary: h.summary };
      }
    } catch { /* fall through */ }
    return { kind: 'none' };
  }
  return (await loadDemo()) ?? { kind: 'none' };
}
